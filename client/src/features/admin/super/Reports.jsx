import {
  ClipboardList,
  Download,
  FileText,
  GraduationCap,
  Wallet,
} from "lucide-react";
import BarList from "../../../components/charts/BarList";
import TrendChart from "../../../components/charts/TrendChart";
import Badge from "../../../components/ui/Badge";
import Button from "../../../components/ui/Button";
import Card, { CardBody, CardHeader } from "../../../components/ui/Card";
import DataTable from "../../../components/ui/Table";
import PageHeader from "../../../components/ui/PageHeader";
import StatCard from "../../../components/ui/StatCard";
import {
  reportSeries,
  superAdminReportKpis,
  superAdminReports,
  superAdminRoleDistribution,
} from "../../../mocks/superAdminData";
import { downloadCsv } from "../../../utils/csv";
import { formatStatus, getStatusVariant } from "../../../utils/status";

const KPI_ICONS = {
  reports: FileText,
  applications: ClipboardList,
  admissions: GraduationCap,
  revenue: Wallet,
};

const reportColumns = [
  {
    key: "name",
    header: "Report",
    render: (report) => (
      <div className="min-w-0">
        <p className="truncate text-xs font-semibold text-eromza-text">
          {report.name}
        </p>
        <p className="mt-1 text-[11px] text-eromza-subtle">{report.id}</p>
      </div>
    ),
  },
  {
    key: "category",
    header: "Category",
    render: (report) => <Badge variant="neutral">{report.category}</Badge>,
  },
  {
    key: "generatedBy",
    header: "Generated by",
    render: (report) => (
      <span className="text-xs text-eromza-muted">{report.generatedBy}</span>
    ),
  },
  {
    key: "generated",
    header: "Date",
    render: (report) => (
      <span className="text-xs text-eromza-muted">{report.generated}</span>
    ),
  },
  {
    key: "status",
    header: "Status",
    render: (report) => (
      <Badge variant={getStatusVariant(report.status)}>
        {formatStatus(report.status)}
      </Badge>
    ),
  },
];

export default function Reports() {
  const handleExport = () => {
    downloadCsv("eromza-platform-report.csv", [
      ["Metric", "Value"],
      ...superAdminReportKpis.map((kpi) => [kpi.label, kpi.value]),
      ...superAdminRoleDistribution.map((item) => [
        `${item.label} accounts`,
        item.value,
      ]),
    ]);
  };

  return (
    <div className="space-y-6">
      <PageHeader
        eyebrow="Analytics"
        title="Reports & Analytics"
        description="Review platform-wide performance, user distribution, and generated operational reports."
        actions={
          <Button onClick={handleExport}>
            <Download size={16} />
            Export report
          </Button>
        }
      />

      <div className="grid gap-4 sm:grid-cols-2 xl:grid-cols-4">
        {superAdminReportKpis.map((kpi) => (
          <StatCard
            key={kpi.id}
            label={kpi.label}
            value={kpi.value}
            change={kpi.change}
            tone={kpi.tone}
            icon={KPI_ICONS[kpi.icon]}
          />
        ))}
      </div>

      <div className="grid gap-5 xl:grid-cols-[minmax(0,1.6fr)_minmax(320px,1fr)]">
        <Card>
          <CardHeader
            title="Reports generated"
            description="Monthly report generation across the platform"
            action={<Badge variant="success">+18.6%</Badge>}
          />
          <CardBody>
            <TrendChart
              labels={reportSeries.labels}
              values={reportSeries.values}
              ariaLabel="Reports generated over the last six months"
            />
          </CardBody>
        </Card>

        <Card>
          <CardHeader
            title="Accounts by role"
            description="Active platform accounts across all roles"
          />
          <CardBody>
            <BarList
              items={superAdminRoleDistribution}
              valueFormatter={(value) =>
                `${value.toLocaleString("en-IN")} users`
              }
            />
          </CardBody>
        </Card>
      </div>

      <Card>
        <CardHeader
          title="Generated reports"
          description="Latest operational reports available across the platform"
          action={<Badge variant="neutral">Live</Badge>}
        />
        <DataTable
          columns={reportColumns}
          rows={superAdminReports}
          emptyTitle="No reports generated"
        />
      </Card>
    </div>
  );
}
